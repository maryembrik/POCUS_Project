def render_report(report: dict) -> str:
    """The report as text, deterministic for a given report object."""
    L: list[str] = []
    a = L.append

    a("=" * 78)
    a(f"CLINICAL REPORT  {report['encounter_id']}")
    a(f"generated {report['generated_at']}   report v{report['report_version']}")
    a("=" * 78)

    a("\nCONCLUSION")
    a("  " + report["conclusion"])

    sev = report["decision_support"]["severity"]
    a(f"\nSEVERITY: {sev['severity']}   (triage {sev['triage_urgency']}, "
      f"escalation {'YES' if sev['escalation'] else 'no'})")
    for r in sev["reasons"]:
        a(f"  - {r}")

    alerts = report["decision_support"]["alerts"]
    ncrit = sum(1 for al in alerts if al["severity"] == "CRITICAL")
    # Counted by severity rather than headed "critical alerts" over a list that also contains
    # warnings, which overstates the first line a reader looks at.
    a(f"\nALERTS: {ncrit} critical, {len(alerts) - ncrit} warning")
    if not alerts:
        a("  none")
    for al in alerts:
        a(f"  [{al['severity']}] {al['type']}: {al['message']}")

    c = report["context"]
    a("\nCONTEXT")
    for k in sorted(c):
        a(f"  {k}: {c[k]}")
    t = report["triage"]
    a(f"  triage: {t['urgency']} (confidence {t['confidence']})"
      if t["urgency"] else "  triage: not available")

    p = report["pocus"]
    a("\nPOCUS FINDINGS")
    if p["detected"]:
        for d in p["detected"]:
            a(f"  DETECTED      {d['organ']}: {d['finding']} "
              f"({d['confidence']:.2f}, evidence {d['evidence']})")
    else:
        a("  DETECTED      none")
    for d in p["screened_not_detected"]:
        a(f"  NOT DETECTED  {d['organ']}: {d['finding']} ({d['confidence']:.2f}) "
          f"-- screened for and not seen")
    if p["not_assessed"]:
        a("  NOT ASSESSED  " + ", ".join(p["not_assessed"]))
        a("                a gap in the record, NOT a negative result")
    for lim in p["model_limitations"]:
        a(f"  LIMIT         {lim}")

    if report["quantitative_measures"]:
        a("\nQUANTITATIVE MEASURES")
        for m in report["quantitative_measures"]:
            a(f"  {m['organ']}: {m['measure']} = {m['value']}")

    v = report["values"]
    a("\nVITALS AND LABORATORY")
    for group in ("vitals", "labs"):
        for k in sorted(v[group]):
            e = v[group][k]
            flag = "" if e.get("flag") == "normal" else f"   <-- {str(e.get('flag')).upper()}"
            ref = f" (ref {e['reference']})" if e.get("reference") else ""
            a(f"  {k}: {e.get('value')} {e.get('unit', '')}{ref}{flag}")
    nm = v["never_measured"]["labs"] + v["never_measured"]["vitals"]
    if nm:
        a("  NEVER MEASURED: " + ", ".join(nm))
        a("                  absent, NOT normal")

    r = report["reasoning"]
    a("\nCLINICAL REASONING")
    if r["withheld"]:
        a("  DIFFERENTIAL WITHHELD -- the generated reasoning did not pass validation")
        for e in (r["withheld_reason"] or []):
            a(f"    - {e}")
        a("  The reasoning below is shown for inspection and is NOT offered as an answer.")
    for i, d in enumerate(r["differential"], 1):
        a(f"  {i}. {d.get('diagnosis')} ({d.get('likelihood')})")
        for s in (d.get("supporting") or []):
            a(f"       supports:  {s}")
        for s in (d.get("contradicting") or []):
            a(f"       against:   {s}")
        for s in (d.get("limitations") or []):
            a(f"       limit:     {s}")
    if r["uncertainty"]:
        a(f"  uncertainty: {r['uncertainty']}")
    if r["evidence_considered"]:
        a("  evidence considered (built from the state, not from the answer):")
        for e in r["evidence_considered"]:
            a(f"    {'*' if e['used'] else ' '} {e['id']} {e['text']}")
    for w in r["warnings"]:
        a(f"  warning: {w}")

    ds = report["decision_support"]
    a("\nRECOMMENDED ADDITIONAL EXAMINATIONS")
    if not ds["additional_examinations"]:
        a("  none -- the record is complete for this presentation")
    for rec in ds["additional_examinations"]:
        a(f"  [{rec['priority']}] {rec['exam']}")
        a(f"          {rec['reason']}")
    a("  The system recommends examinations; it does not order them.")

    th = ds["therapeutic"]
    a("\nTHERAPEUTIC CONSIDERATIONS")
    if not th["considerations"]:
        a(f"  none -- {th['status']}")
        if th.get("note"):
            a(f"  {th['note']}")
    for c_ in th["considerations"]:
        a(f"  CONSIDER: {c_['consideration']}")
        a(f"    basis: {c_['basis']} [{c_['passage']}]")
        a(f"    {c_['disclaimer']}")

    s = report["safety"]
    esc = s["escalation"] or {}
    a("\nSAFETY")
    a(f"  escalation: {'YES' if esc.get('escalate') else 'no'}  route {esc.get('route')}")
    for t_ in (esc.get("triggers") or []):
        a(f"    - {t_}")
    if s["conflicts"]:
        for c_ in s["conflicts"]:
            a(f"  conflict: {c_}")
    q = s["case_quality"] or {}
    a(f"  case quality: {q.get('grade')}")
    a(f"  alert thresholds: config v{s.get('thresholds_version')}")

    a("\n" + "-" * 78)
    a(DISCLAIMER)
    a("=" * 78)
    return "\n".join(L)


