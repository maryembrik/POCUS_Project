"""Module 5 -- automated clinical reporting and archiving.

Assembles one standardised report from the encounter: context, triage, POCUS findings,
quantitative measures, reasoning, decision support, and the safety envelope. Renders it
deterministically, and archives it with a content hash so that what was shown to a clinician
can be recovered later and proven unaltered.

Two decisions in here are safety decisions rather than presentation ones.

**NOT ASSESSED is a section, not an omission.** A modality that was never examined gets its
own heading in the report, next to what was found and what was screened for and not found.
Omitting it would leave a reader to infer absence from silence, and silence is what a normal
result looks like. The three-state distinction the schema preserves is worth nothing if the
report collapses it at the last step.

**A withheld differential is rendered as withheld.** The report does not quietly drop the
reasoning section when validation failed; it prints the refusal and the reason. A report that
simply lacks a differential is indistinguishable from one where the model was never asked.
"""
from __future__ import annotations

import hashlib
import json
import os
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

REPORT_VERSION = "1.0"

DISCLAIMER = (
    "Generated by an AI decision-support prototype. Not a diagnostic device. Not validated "
    "against clinical outcomes. Every finding, alert and recommendation requires clinician "
    "verification, and the clinical decision remains the clinician's.")


def build_report(state: dict, result: dict, support: dict) -> dict[str, Any]:
    """The structured report. `result` is reason()'s output; `support` is decision_support()'s.

    Pure assembly: every value here already exists upstream and nothing is recomputed, so the
    report cannot disagree with the system that produced it.
    """
    imaging = state["imaging"]
    detected = [f for f in imaging["findings"] if f["detected"]]
    screened = [f for f in imaging["findings"] if not f["detected"]]
    diff = result.get("differential") or {}
    withheld = bool(result.get("differential_withheld"))

    # Quantitative measures reported by the modules, e.g. an ejection fraction.
    measures: list[dict[str, Any]] = []
    for organ, rep in (state.get("_reports") or {}).items():
        for name, value in (rep.get("measurements") or {}).items():
            measures.append({"organ": organ, "measure": name, "value": value})

    report: dict[str, Any] = {
        "report_version": REPORT_VERSION,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "encounter_id": state.get("encounter_id"),

        "context": {
            **(state.get("demographics") or {}),
            "scenario": support["scenario"]["label"],
            "scenario_matched_on": support["scenario"].get("matched_on"),
        },

        "triage": {
            "urgency": (state.get("triage") or {}).get("urgency"),
            "confidence": (state.get("triage") or {}).get("confidence"),
            # Present only when a model proposed a tier for this encounter. The archived record
            # is where this belongs: it is not something a clinician needs while assessing the
            # patient, and it is exactly what someone reviewing the encounter afterwards --
            # or auditing how the two assessments compare over many encounters -- would need.
            "agreement": state.get("triage_agreement"),
        },

        "pocus": {
            "detected": [{"organ": f["organ"], "finding": f["label"],
                          "confidence": f["confidence"], "evidence": f["evidence"]}
                         for f in detected],
            "screened_not_detected": [{"organ": f["organ"], "finding": f["label"],
                                       "confidence": f["confidence"]} for f in screened],
            # Its own key, deliberately. See the module docstring.
            "not_assessed": sorted(set(list(imaging.get("organs_not_assessed") or [])
                                       + list(support["scenario"].get("not_assessed") or []))),
            "model_limitations": list(imaging.get("out_of_scope") or []),
        },

        "quantitative_measures": measures,

        "values": {
            "vitals": state.get("vitals") or {},
            "labs": state.get("labs") or {},
            "never_measured": {"labs": state["missing"]["labs"],
                               "vitals": state["missing"]["vitals"]},
        },

        "reasoning": {
            "withheld": withheld,
            "withheld_reason": result.get("validation_errors") if withheld else None,
            "differential": diff.get("differential") or [],
            "uncertainty": diff.get("uncertainty"),
            "missing_information": diff.get("missing_information") or [],
            "warnings": result.get("warnings") or [],
            "evidence_considered": result.get("evidence_considered") or [],
            "retrieval": result.get("retrieval"),
        },

        "decision_support": {
            "severity": support["severity"],
            "alerts": support["alerts"],
            "additional_examinations": support["additional_examinations"],
            "therapeutic": support["therapeutic"],
        },

        "safety": {
            "escalation": result.get("escalation"),
            "case_quality": state.get("case_quality"),
            "conflicts": state.get("conflicts") or [],
            "thresholds_version": support.get("thresholds_version"),
            "disclaimer": DISCLAIMER,
        },
    }

    report["conclusion"] = standardised_conclusion(report)
    return report


def standardised_conclusion(report: dict) -> str:
    """One paragraph, assembled from the report by fixed rules.

    Written by template rather than by the model on purpose. The conclusion is the line a busy
    reader will act on, and it must say the same thing as the rest of the report; generating it
    would introduce a place where it could differ.
    """
    sev = report["decision_support"]["severity"]
    esc = report["safety"]["escalation"] or {}
    p = report["pocus"]
    parts: list[str] = []

    parts.append(f"{report['context'].get('scenario', 'Unclassified')} presentation assessed "
                 f"at {sev['severity']} severity.")

    if p["detected"]:
        found = ", ".join(f"{d['finding']} ({d['organ']}, {d['confidence']:.2f})"
                          for d in p["detected"])
        parts.append(f"Point-of-care ultrasound detected {found}.")
    elif p["screened_not_detected"]:
        parts.append(f"Point-of-care ultrasound screened "
                     f"{len(p['screened_not_detected'])} finding(s) and detected none; this "
                     f"does not exclude pathology the models do not represent.")
    else:
        parts.append("No point-of-care ultrasound finding is recorded.")

    if p["not_assessed"]:
        parts.append(f"NOT ASSESSED: {', '.join(p['not_assessed'])} — expected for this "
                     f"presentation and never examined.")

    crit = [a for a in report["decision_support"]["alerts"] if a["severity"] == "CRITICAL"]
    if crit:
        parts.append(f"{len(crit)} critical alert(s): "
                     f"{'; '.join(a['message'] for a in crit)}.")

    if report["reasoning"]["withheld"]:
        parts.append("The differential was WITHHELD because the generated reasoning did not "
                     "pass validation against the record.")
    elif report["reasoning"]["differential"]:
        top = report["reasoning"]["differential"][0]
        parts.append(f"Leading consideration: {top.get('diagnosis')} "
                     f"({top.get('likelihood')} likelihood).")

    if esc.get("escalate"):
        parts.append(f"ESCALATED — {len(esc.get('triggers') or [])} trigger(s); route "
                     f"{esc.get('route')}.")
    else:
        parts.append("No escalation trigger; the case may be answered directly.")

    high = [r for r in report["decision_support"]["additional_examinations"]
            if r["priority"] == "HIGH"]
    if high:
        parts.append(f"Most informative next: {', '.join(r['exam'] for r in high[:3])}.")

    return " ".join(parts)


