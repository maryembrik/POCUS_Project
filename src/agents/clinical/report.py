def archive_report(report: dict, root: str | Path, *, text: str | None = None) -> dict[str, str]:
    """Write the report to the archive, atomically, with a content hash.

    The hash is over the canonical JSON with the generation timestamp removed, so the same
    encounter reprocessed by the same system produces the same digest and a genuine change is
    distinguishable from a re-run. Writes go through a temporary file and a replace, because a
    half-written report that still parses would be worse than none.
    """
    root = Path(root)
    (root / "reports").mkdir(parents=True, exist_ok=True)

    stable = {k: v for k, v in report.items() if k != "generated_at"}
    digest = hashlib.sha256(
        json.dumps(stable, sort_keys=True, default=str).encode("utf8")).hexdigest()
    report = {**report, "content_sha256": digest}

    eid = report.get("encounter_id") or "unknown"
    paths = {}
    for suffix, payload in (("json", json.dumps(report, indent=2, default=str)),
                            ("txt", text if text is not None else render_report(report))):
        dest = root / "reports" / f"{eid}.{suffix}"
        fd, tmp = tempfile.mkstemp(dir=dest.parent, suffix=f".{suffix}.tmp")
        with os.fdopen(fd, "w", encoding="utf8") as fh:
            fh.write(payload)
        os.replace(tmp, dest)
        paths[suffix] = str(dest)

    return {**paths, "sha256": digest}
